from __future__ import annotations

import os
from pathlib import Path
from tempfile import NamedTemporaryFile
from typing import Any

import yaml
from pydantic import ValidationError

from oh_goon.core.errors import FleetPlanInvalid
from oh_goon.core.execution_lock_identity import LOCK_VERSION
from oh_goon.core.models.execution_lock_models import ExecutionLock
from oh_goon.core.path_authority import navigation_path

LOCK_FILE_NAME = "goon.lock"
_GENERATED_COMMENT = "# Generated by Oh Goon. Do not edit manually.\n"


def render_execution_lock(lock: ExecutionLock) -> str:
    payload: dict[str, Any] = {
        "lock_version": lock.lock_version,
        "plan": lock.plan,
        "execution": [
            item.model_dump(mode="json", exclude_computed_fields=True) for item in lock.execution
        ],
    }
    if lock.external:
        payload["external"] = {item.path: item.digest for item in lock.external}
    payload["digest"] = lock.digest
    return _GENERATED_COMMENT + yaml.safe_dump(
        payload,
        sort_keys=False,
        allow_unicode=False,
        default_flow_style=False,
    )


def parse_execution_lock(text: str) -> ExecutionLock:
    try:
        payload = yaml.safe_load(text)
    except yaml.YAMLError as exc:
        raise FleetPlanInvalid(f"Malformed goon.lock: {exc}") from exc
    if not isinstance(payload, dict):
        raise FleetPlanInvalid("Malformed goon.lock: top level must be a mapping")
    version = payload.get("lock_version")
    if version != LOCK_VERSION:
        raise FleetPlanInvalid(f"Unsupported goon.lock version: {version!r}; expected 1")
    external = payload.get("external", {})
    if not isinstance(external, dict):
        raise FleetPlanInvalid("Malformed goon.lock: external must be a path-to-digest mapping")
    normalized = dict(payload)
    normalized["external"] = [{"path": path, "digest": digest} for path, digest in external.items()]
    try:
        return ExecutionLock.model_validate(normalized)
    except ValidationError as exc:
        raise FleetPlanInvalid(f"Malformed goon.lock: {exc}") from exc


def write_execution_lock(path: Path, lock: ExecutionLock) -> None:
    destination = navigation_path(path)
    destination.parent.mkdir(parents=True, exist_ok=True)
    rendered = render_execution_lock(lock)
    temp_name: str | None = None
    try:
        with NamedTemporaryFile(
            mode="w",
            encoding="utf-8",
            newline="\n",
            dir=destination.parent,
            prefix=f".{destination.name}.",
            suffix=".tmp",
            delete=False,
        ) as handle:
            temp_name = handle.name
            handle.write(rendered)
            handle.flush()
            os.fsync(handle.fileno())
        os.replace(temp_name, destination)
        temp_name = None
    finally:
        if temp_name is not None:
            Path(temp_name).unlink(missing_ok=True)


def load_execution_lock(path: Path) -> ExecutionLock:
    lock_path = navigation_path(path)
    if not lock_path.is_file():
        raise FleetPlanInvalid(
            f"Locked execution requires {LOCK_FILE_NAME}; run 'oh-goon lock' to generate it"
        )
    try:
        return parse_execution_lock(lock_path.read_text(encoding="utf-8"))
    except (OSError, UnicodeError) as exc:
        raise FleetPlanInvalid(f"Cannot read goon.lock: {exc}") from exc
