from pathlib import Path
from typing import Protocol


class ExclusionStore(Protocol):
    def get(self, repository: Path | str) -> dict[str, str] | None: ...

    def exclude(self, repository: Path | str, reason: str) -> dict[str, str]: ...

    def include(self, repository: Path | str) -> bool: ...

    def list(self) -> list[dict[str, str]]: ...
